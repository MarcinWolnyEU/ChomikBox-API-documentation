<?php

declare(strict_types=1);

namespace ChomikBox\Tests\Support;

/**
 * Tiny self-generated payloads for upload tests (no GD needed).
 */
final class TestFiles
{
    public static function text(string $label): string
    {
        return "ChomikBox API test file ($label)\n"
            . "This file was generated by the PHP client test-suite and uploaded to a sandbox folder.\n"
            . str_repeat("0123456789 abcdefghijklmnopqrstuvwxyz\n", 24);
    }

    /** 1 s silent mono MP3 (1248 bytes), generated with: ffmpeg -f lavfi -i anullsrc=r=22050:cl=mono -t 1 -q:a 9 -map_metadata -1 -id3v2_version 0 */
    public static function silentMp3(): string
    {
        return (string) file_get_contents(dirname(__DIR__) . '/fixtures/silent-1s.mp3');
    }

    /** RGB gradient PNG, filter type 0, zlib-compressed IDAT. */
    public static function png(int $width = 64, int $height = 48): string
    {
        $raw = '';
        for ($y = 0; $y < $height; $y++) {
            $raw .= "\0";
            for ($x = 0; $x < $width; $x++) {
                $raw .= chr(intdiv(255 * $x, max(1, $width - 1))) . chr(intdiv(255 * $y, max(1, $height - 1))) . chr(128);
            }
        }
        $chunk = static fn (string $type, string $data): string =>
            pack('N', strlen($data)) . $type . $data . pack('N', crc32($type . $data));

        return "\x89PNG\r\n\x1a\n"
            . $chunk('IHDR', pack('NNCCCCC', $width, $height, 8, 2, 0, 0, 0))
            . $chunk('IDAT', (string) gzcompress($raw, 9))
            . $chunk('IEND', '');
    }

    /**
     * Minimal baseline JPEG of a uniform grey level (DC-only, quantiser 1).
     * Width/height must be multiples of 8. Used as client-side thumbnail.
     */
    public static function jpeg(int $width = 64, int $height = 48, int $grey = 200): string
    {
        if ($width % 8 || $height % 8) {
            throw new \InvalidArgumentException('JPEG size must be a multiple of 8');
        }
        $dc = 8 * ($grey - 128);                       // F(0,0) of a uniform block
        $cat = $dc === 0 ? 0 : (int) floor(log(abs($dc), 2)) + 1;
        $bits = $dc >= 0 ? $dc : $dc + (1 << $cat) - 1; // JPEG magnitude encoding

        $seg = static fn (int $marker, string $data): string => pack('CC', 0xFF, $marker) . pack('n', strlen($data) + 2) . $data;
        $out = "\xFF\xD8";
        $out .= $seg(0xE0, "JFIF\0\x01\x01\x00\x00\x01\x00\x01\x00\x00");
        $out .= $seg(0xDB, "\x00" . str_repeat("\x01", 64));
        $out .= $seg(0xC0, pack('CnnC', 8, $height, $width, 1) . "\x01\x11\x00");
        // DC table: two 2-bit codes: 00 -> category 0, 01 -> category $cat
        $out .= $seg(0xC4, "\x00" . "\x00\x02" . str_repeat("\x00", 14) . chr(0) . chr($cat));
        // AC table: one 1-bit code: 0 -> EOB
        $out .= $seg(0xC4, "\x10" . "\x01" . str_repeat("\x00", 15) . "\x00");
        $out .= $seg(0xDA, "\x01\x01\x00\x00\x3F\x00");

        $bitstr = '';
        $blocks = ($width / 8) * ($height / 8);
        for ($i = 0; $i < $blocks; $i++) {
            if ($i === 0 && $cat > 0) {
                $bitstr .= '01' . str_pad(decbin($bits), $cat, '0', STR_PAD_LEFT);
            } else {
                $bitstr .= '00';
            }
            $bitstr .= '0'; // EOB
        }
        $bitstr .= str_repeat('1', (8 - strlen($bitstr) % 8) % 8);
        $data = '';
        foreach (str_split($bitstr, 8) as $byte) {
            $b = chr(bindec($byte));
            $data .= $b === "\xFF" ? "\xFF\x00" : $b;
        }
        return $out . $data . "\xFF\xD9";
    }
}
