#!/usr/bin/env node
// Generates the canonical, strictly OAS 3.2.1-conformant document
//   api/chomikbox.openapi.yaml
// from the authoring source (per-operation view)
//   api/chomikbox.per-operation.openapi.yaml
//
//   node tools/build-strict.mjs            write chomikbox.openapi.yaml
//   node tools/build-strict.mjs --check    exit 1 if the file on disk is stale
//
// Deterministic: output depends only on the source document (and, for the
// x-intentionally-invalid markers, on the schema walker). validate.mjs check
// (i) rebuilds it in memory and requires byte equality, so the two documents
// cannot drift.
//
// Transformation:
// - the 17 main-service SOAP path items (the ones using the declared `?op=`
//   server deviation) are removed and merged into ONE `post` on the physical
//   endpoint /services/ChomikBoxService.svc (operationId callSoapService),
//   together with the service-level probes that the source documents on that
//   same post (operationId soapEndpoint);
// - SOAPAction becomes a required header with an enum of the 17 actions;
// - request/response bodies become `oneOf` of the per-operation envelope
//   schemas (SoapRequestEnvelope / SoapResponseEnvelope); faults keep
//   SoapFaultEnvelope;
// - every example is kept, renamed `<Operation>.<case>`;
// - per-operation information moves to the root map `x-soap-operations`
//   (action -> operation, summary, description, schema refs, example names,
//   x-verification, x-session, x-discrepancies, x-evidence, x-security-notes,
//   x-untested-parameters, pointer to the per-operation view);
// - `x-oas-deviation` and the per-operation text blocks of info.description
//   are replaced; all other paths, components and examples are copied as is.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseExact, toYaml } from './lib/yamlio.mjs';
import { XmlSchemaWalker } from './lib/xmlwalk.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const API = path.resolve(here, '..');
export const SOURCE_YAML = path.join(API, 'chomikbox.per-operation.openapi.yaml');
export const STRICT_YAML = path.join(API, 'chomikbox.openapi.yaml');
export const STRICT_OP_ID = 'callSoapService';
const ENDPOINT = '/services/ChomikBoxService.svc';
const SCHEMA = (n) => `#/components/schemas/${n}`;

const STRICT_HEADER = `# ChomikBox 2.0.8.2 network API - CANONICAL, strictly conformant OpenAPI 3.2.1 description.
# GENERATED by tools/build-strict.mjs from chomikbox.per-operation.openapi.yaml - do not edit by hand.
# SOAP is modelled as one POST on the physical endpoint; per-operation detail is in x-soap-operations.
`;

const STRICT_CONVENTIONS = `## SOAP in OpenAPI: conventions of this canonical document

**One operation for the whole SOAP service.** WCF dispatches every SOAP call on the \`SOAPAction\` header; the URL is always the physical endpoint \`POST http://box.chomikuj.pl/services/ChomikBoxService.svc\` (\`https://\` works too, the client never uses it). Path suffixes (\`.svc/Auth\`) fail with \`a:DestinationUnreachable\` and matrix parameters (\`.svc;Auth\`) redirect, and OAS 3.2.1 §4.5.1 forbids a query in a server URL, so a conformant document cannot give each SOAP operation its own URL. This document therefore models the service as **one \`post\`** (\`operationId: ${STRICT_OP_ID}\`) with:
- a required \`SOAPAction\` header parameter whose \`enum\` lists the 17 actions of the main service (SessionBegin, which targets a separate session host, keeps its own path \`/session\`);
- a request body \`SoapRequestEnvelope\` = \`oneOf\` the 17 per-operation \`<Op>RequestEnvelope\` schemas, and a 200 response \`SoapResponseEnvelope\` = \`oneOf\` the 17 \`<Op>ResponseEnvelope\` schemas (the selected branch must correspond to the SOAPAction); HTTP 500 carries \`SoapFaultEnvelope\`;
- every captured example, named \`<Operation>.<case>\` (e.g. \`Auth.success\`, \`Folders.sandbox-depth0\`); examples named \`Service.*\` / \`SessionBegin.*\` document how the endpoint reacts to unknown actions, wrong namespaces and undeserialisable values (marked \`x-intentionally-invalid\` where the body matches no operation envelope);
- the root map **\`x-soap-operations\`**: for each SOAPAction the operation name, summary, description, request/response/fault schema references, example names, \`x-verification\`, \`x-session\`, \`x-discrepancies\`, \`x-evidence\`, \`x-security-notes\` and \`x-untested-parameters\`, plus a pointer to the per-operation view.

**Companion document.** \`chomikbox.per-operation.openapi.yaml\` presents the same operations with one path item each (\`/Auth\`, \`/Folders\`, …). It needs a server URL with a query (\`…svc?op=\`), a deliberate and declared deviation from OAS 3.2.1, and it is the authoring source from which this document is generated (\`tools/build-strict.mjs\`). Physical endpoint, SOAPAction dispatch, schemas and examples are identical in both; \`tools/validate.mjs\` checks the equivalence.`;

const COMPANION_NOTE = '> **Canonical document.** This is the strictly conformant OpenAPI 3.2.1 description (no query or fragment in any server URL). A per-operation view of the same SOAP operations, `chomikbox.per-operation.openapi.yaml`, exists for readers and tools that prefer one path item per operation; it carries a declared deviation (`x-oas-deviation`).';

const exDir = (ex) => (/^examples\/([^/]+)\//.exec(ex?.['x-externalValue'] || '') || [])[1];
const stripRouting = (text) => text.split('\n\n').filter((para) => !para.startsWith('**Routing.**')).join('\n\n');
function replaceBlock(text, name, replacement) {
  const re = new RegExp(`<!-- variant:${name} -->[\\s\\S]*?<!-- /variant:${name} -->`);
  if (!re.test(text)) throw new Error(`info.description: block variant:${name} not found`);
  return text.replace(re, replacement);
}
const isDeviationPath = (pi) => (pi.servers || []).some((s) => /[?#]/.test(s.url));

export function buildStrict(source) {
  const doc = structuredClone(source);
  const deref = (o) => { let x = o; while (x && x.$ref) x = x.$ref.slice(2).split('/').reduce((a, k) => a[k], doc); return x; };

  // ---- 1. collect the main-service SOAP operations (declared deviation paths)
  const soapPaths = Object.entries(doc.paths).filter(([, pi]) => isDeviationPath(pi));
  const dev = doc['x-oas-deviation'];
  if (!dev) throw new Error('source has no x-oas-deviation');
  const devSet = new Set(dev.paths);
  if (soapPaths.length !== devSet.size || soapPaths.some(([p]) => !devSet.has(p))) throw new Error('deviation paths in source do not match x-oas-deviation.paths');

  const actions = [];
  const soapOps = {};
  const req = {}; // media -> examples
  const resp = {}; // code -> examples
  const add = (bucket, key, name, ex) => { (bucket[key] ??= {})[name] = ex; };
  const seen = new Set(); // `${slot}|${x-externalValue}` for de-duplication
  const slotKey = (slot, ex) => `${slot}|${deref(ex)?.['x-externalValue'] ?? JSON.stringify(ex)}`;
  const notes = new Map();
  const evidence = { examples: [] };
  const mergeEvidence = (ev) => {
    for (const v of ev?.examples || []) if (!evidence.examples.includes(v)) evidence.examples.push(v);
  };
  const groups = new Set();
  let verification = 'verified-live';

  for (const [p, pi] of soapPaths) {
    const op = pi.post;
    if (!op || !op['x-soap-action']) throw new Error(`deviation path ${p} is not a SOAP post`);
    const action = op['x-soap-action'];
    const name = action.split('/').pop();
    actions.push(action);
    const exNames = { request: [], responses: {} };
    for (const [media, mt] of Object.entries(op.requestBody?.content || {})) {
      for (const [k, ex] of Object.entries(mt.examples || {})) {
        const n = `${name}.${k}`;
        add(req, media, n, ex); seen.add(slotKey(`req:${media}`, ex)); exNames.request.push(n);
      }
    }
    for (const [code, r] of Object.entries(op.responses || {})) {
      if (r.$ref) continue; // shared SoapFault: generic examples come from the endpoint post
      for (const mt of Object.values(r.content || {})) {
        for (const [k, ex] of Object.entries(mt.examples || {})) {
          const n = `${name}.${k}`;
          add(resp, code, n, ex); seen.add(slotKey(`resp:${code}`, ex)); (exNames.responses[code] ??= []).push(n);
        }
      }
    }
    const group = (op.tags || []).find((t) => !['verified-live', 'partially-verified', 'unverified', 'probe'].includes(t));
    groups.add(group);
    if (op['x-verification'] !== 'verified-live') verification = 'partially-verified';
    for (const s of op['x-security-notes'] || []) notes.set(s.id, s);
    mergeEvidence(op['x-evidence']);
    soapOps[action] = {
      operation: name,
      summary: op.summary,
      description: stripRouting(op.description),
      group,
      endpoint: { path: ENDPOINT, method: 'post', operationId: STRICT_OP_ID },
      perOperationView: { document: 'chomikbox.per-operation.openapi.yaml', path: p, operationId: op.operationId },
      requestSchema: op.requestBody.content['text/xml'].schema.$ref,
      responseSchema: op.responses['200'].content['text/xml'].schema.$ref,
      faultSchema: SCHEMA('SoapFaultEnvelope'),
      examples: exNames,
      'x-verification': op['x-verification'],
      ...(op['x-session'] ? { 'x-session': op['x-session'] } : {}),
      ...(op['x-discrepancies'] ? { 'x-discrepancies': op['x-discrepancies'] } : {}),
      'x-evidence': op['x-evidence'],
      ...(op['x-security-notes'] ? { 'x-security-notes': op['x-security-notes'] } : {}),
      ...(op['x-untested-parameters'] ? { 'x-untested-parameters': op['x-untested-parameters'] } : {}),
    };
    delete doc.paths[p];
  }

  // SessionBegin (own host/path) is listed too, pointing at its operation.
  for (const [p, pi] of Object.entries(doc.paths)) {
    for (const [m, op] of Object.entries(pi)) {
      if (!['get', 'post', 'put', 'delete', 'head', 'patch', 'options', 'trace', 'query'].includes(m) || !op?.['x-soap-action']) continue;
      const exNames = { request: Object.keys(op.requestBody?.content?.['text/xml']?.examples || {}), responses: {} };
      for (const [code, r] of Object.entries(op.responses || {})) if (!r.$ref) for (const mt of Object.values(r.content || {})) exNames.responses[code] = Object.keys(mt.examples || {});
      soapOps[op['x-soap-action']] = {
        operation: op['x-soap-action'].split('/').pop(),
        summary: op.summary,
        description: op.description,
        group: (op.tags || []).find((t) => !['verified-live', 'partially-verified', 'unverified', 'probe'].includes(t)),
        endpoint: { path: p, method: m, operationId: op.operationId },
        note: 'Not on the main service: posted to the session host (see the operation at this path).',
        requestSchema: op.requestBody.content['text/xml'].schema.$ref,
        responseSchema: op.responses['200'].content['text/xml'].schema.$ref,
        faultSchema: SCHEMA('SoapFaultEnvelope'),
        examples: exNames,
        'x-verification': op['x-verification'],
        ...(op['x-session'] ? { 'x-session': op['x-session'] } : {}),
        ...(op['x-discrepancies'] ? { 'x-discrepancies': op['x-discrepancies'] } : {}),
        'x-evidence': op['x-evidence'],
        ...(op['x-security-notes'] ? { 'x-security-notes': op['x-security-notes'] } : {}),
      };
    }
  }

  // ---- 2. merge the service-level post (probes) of the physical endpoint
  const svc = doc.paths[ENDPOINT];
  if (!svc?.post) throw new Error(`source has no post on ${ENDPOINT}`);
  const generic = svc.post;
  for (const s of generic['x-security-notes'] || []) notes.set(s.id, s);
  mergeEvidence(generic['x-evidence']);
  const genericNames = (slot, bucket, key, examples) => {
    for (const [k, ex] of Object.entries(examples || {})) {
      if (seen.has(slotKey(slot, ex))) continue; // same capture already present under its operation
      add(bucket, key, `${exDir(deref(ex)) || 'Service'}.${k}`, ex);
    }
  };
  for (const [media, mt] of Object.entries(generic.requestBody?.content || {})) genericNames(`req:${media}`, req, media, mt.examples);
  const extraResponses = {};
  for (const [code, r] of Object.entries(generic.responses || {})) {
    if (r.content) for (const mt of Object.values(r.content)) genericNames(`resp:${code}`, resp, code, mt.examples);
    if (r['x-response-examples']) {
      extraResponses[code] = { ...r, 'x-response-examples': Object.fromEntries(Object.entries(r['x-response-examples']).map(([k, ex]) => [`${exDir(ex) || 'Service'}.${k}`, ex])) };
    }
  }

  // ---- 3. components: oneOf envelopes
  const reqRefs = actions.map((a) => soapOps[a].requestSchema);
  const respRefs = actions.map((a) => soapOps[a].responseSchema);
  doc.components.schemas.SoapRequestEnvelope = {
    description: `Request body of \`${STRICT_OP_ID}\`: exactly one of the ${actions.length} per-operation request envelopes. The branch must correspond to the \`SOAPAction\` header (\`x-soap-operations\` maps each action to its schema). Wrapper only: \`xml.nodeType: none\`, the XML document is the selected \`<s:Envelope>\`.`,
    xml: { nodeType: 'none' },
    oneOf: reqRefs.map(($ref) => ({ $ref })),
  };
  doc.components.schemas.SoapResponseEnvelope = {
    description: `HTTP 200 body of \`${STRICT_OP_ID}\`: exactly one of the ${actions.length} per-operation response envelopes, selected by the \`SOAPAction\` of the request. Service-level errors (\`BadToken\`, \`Error\`, …) are in the result's \`status\`. Wrapper only: \`xml.nodeType: none\`.`,
    xml: { nodeType: 'none' },
    oneOf: respRefs.map(($ref) => ({ $ref })),
  };
  delete doc.components.schemas.AnySoapResponseEnvelope; // only used by the source's generic 200

  // ---- 4. mark examples that match no operation envelope
  const walker = new XmlSchemaWalker(doc);
  const markInvalid = (examples, schemaRef) => {
    for (const [k, ex0] of Object.entries(examples)) {
      if (ex0.$ref) continue;
      if (ex0['x-intentionally-invalid'] || typeof ex0.serializedValue !== 'string') continue;
      const r = walker.validateDocument(ex0.serializedValue, { $ref: schemaRef });
      if (!r.ok) examples[k] = { ...ex0, 'x-intentionally-invalid': 'The body matches none of the 17 operation envelopes (unknown action, wrong namespace or undeserialisable value); kept to document the service\'s fault behaviour.' };
    }
  };
  for (const media of Object.keys(req)) markInvalid(req[media], SCHEMA('SoapRequestEnvelope'));

  // ---- 5. the single SOAP operation
  const firstOp = soapPaths[0][1].post;
  const contentEncoding = firstOp.parameters.find((x) => x.name === 'Content-Encoding');
  const table = actions.map((a) => {
    const o = soapOps[a];
    return `| \`${o.operation}\` | ${o.summary} | \`${o.requestSchema.split('/').pop()}\` | \`${o.responseSchema.split('/').pop()}\` | ${o['x-verification']} |`;
  }).join('\n');
  const strictOp = {
    operationId: STRICT_OP_ID,
    summary: 'Call a ChomikBoxService SOAP operation (dispatch by SOAPAction)',
    description: `All ${actions.length} SOAP operations of the main service share this one physical endpoint; WCF selects the operation by the \`SOAPAction\` header (\`http://chomikuj.pl/IChomikBoxService/<Operation>\`, sent unquoted by the client). The request body is that operation's envelope (\`SoapRequestEnvelope\` = \`oneOf\`), the 200 response its response envelope (\`SoapResponseEnvelope\` = \`oneOf\`). Full per-operation documentation (descriptions, client triggers, discrepancies, evidence, security notes) is in the root map \`x-soap-operations\`, keyed by SOAPAction.

| Operation | Summary | Request schema | Response schema | Verification |
|---|---|---|---|---|
${table}

**Wire format.** \`POST\` with \`Content-Type: text/xml;charset=utf-8\` (exact client bytes; the server answers \`text/xml; charset=utf-8\`). SOAP 1.1 envelope, UTF-8, no indentation, parameters in the documented order (WCF silently drops out-of-order parameters). The client gzips the body (\`Content-Encoding: gzip\`). Service-level outcomes, including errors, are HTTP 200 with \`<Op>Result/status\`; HTTP 500 is a WCF fault.

${generic.description}`,
    tags: ['SOAP service', verification],
    security: [],
    parameters: [
      {
        name: 'SOAPAction',
        in: 'header',
        required: true,
        description: 'WCF dispatch key: selects the operation, and with it the request and response envelope (see `x-soap-operations`). Sent unquoted by the client; a quoted value works too. A missing or unknown action gives `a:ActionNotSupported` (HTTP 500, examples `Service.missing-soapaction`, `Service.action-not-supported`, `SessionBegin.main-endpoint-not-supported`).',
        schema: { type: 'string', enum: actions },
        examples: Object.fromEntries(actions.map((a) => [soapOps[a].operation, { summary: soapOps[a].summary, dataValue: a }])),
      },
      contentEncoding,
    ],
    requestBody: {
      required: true,
      description: 'SOAP 1.1 request envelope of the operation named by `SOAPAction` (media type `text/xml`, UTF-8). `application/soap+xml` (SOAP 1.2) is rejected with 415.',
      content: Object.fromEntries(Object.entries(generic.requestBody.content).map(([media, mt]) => [media, {
        schema: { $ref: SCHEMA('SoapRequestEnvelope') },
        ...(req[media] ? { examples: req[media] } : {}),
      }])),
    },
    responses: {
      200: {
        description: 'Response envelope of the selected operation. HTTP 200 is used for every service-level outcome, including errors: check `<Op>Result/status`. Compressed (`Content-Encoding: gzip`) when the request accepts gzip.',
        content: { 'text/xml': { schema: { $ref: SCHEMA('SoapResponseEnvelope') }, examples: resp['200'] || {} } },
      },
      ...(extraResponses['415'] ? { 415: extraResponses['415'] } : {}),
      500: {
        description: 'WCF SOAP fault (HTTP 500, not compressed): empty/malformed body (`a:InternalServiceFault`), undeserialisable value (`a:DeserializationFailed`), unknown or missing SOAPAction (`a:ActionNotSupported`), and operation-specific crashes (`Auth.empty-request`, `Download.id-hamster-slash-folder`, `MoveFolder.into-itself`).',
        content: { 'text/xml': { schema: { $ref: SCHEMA('SoapFaultEnvelope') }, examples: resp['500'] || {} } },
        ...(doc.components.responses.SoapFault?.['x-security-notes'] ? { 'x-security-notes': doc.components.responses.SoapFault['x-security-notes'] } : {}),
      },
    },
    'x-verification': verification,
    'x-session': { tokenRequired: 'every action except Auth (see x-soap-operations.<action>.x-session)', issuedBy: 'http://chomikuj.pl/IChomikBoxService/Auth' },
    'x-evidence': { examples: [...evidence.examples].sort() },
    'x-security-notes': [...notes.values()].sort((a, b) => a.id.localeCompare(b.id)),
  };
  svc.post = strictOp;

  // ---- 6. document-level edits
  doc['x-soap-operations'] = soapOps;
  delete doc['x-oas-deviation'];
  const used = new Set();
  for (const pi of Object.values(doc.paths)) for (const op of Object.values(pi)) for (const t of op?.tags || []) used.add(t);
  doc.tags = [...doc.tags.filter((t) => t.name !== 'SOAP service'), { name: 'SOAP service', summary: 'The 17 SOAP operations (one endpoint)', parent: 'Client API', kind: 'nav', description: 'One `post` on the physical WCF endpoint; the operation is selected by `SOAPAction`. Per-operation detail: `x-soap-operations`.' }];
  used.add('SOAP service');
  const parents = new Set(doc.tags.filter((t) => used.has(t.name)).map((t) => t.parent).filter(Boolean));
  doc.tags = doc.tags.filter((t) => used.has(t.name) || parents.has(t.name));

  let d = doc.info.description;
  d = replaceBlock(d, 'deviation', COMPANION_NOTE);
  d = replaceBlock(d, 'soap-conventions', STRICT_CONVENTIONS);
  d = replaceBlock(d, 'summary', verificationSummary(doc));
  doc.info.description = d;
  return doc;
}

function verificationSummary(doc) {
  const groups = {};
  let probes = 0;
  let total = 0;
  for (const pi of Object.values(doc.paths)) for (const op of Object.values(pi)) {
    if (!op?.operationId) continue;
    total++;
    (groups[op['x-verification']] ??= []).push(op.operationId);
    if (op['x-probe']) probes++;
  }
  const order = ['verified-live', 'partially-verified', 'unverified'];
  const head = order.filter((k) => groups[k]).map((k) => (k === 'verified-live' && probes ? `${groups[k].length} verified-live (${groups[k].length - probes} client-facing + ${probes} probes)` : `${groups[k].length} ${k}`)).join(', ');
  const lines = [`Current status (${total} operations; the 17 main-service SOAP operations are one operation here, listed individually in \`x-soap-operations\`): ${head}.`];
  for (const k of order) if (groups[k] && k !== 'verified-live') lines.push(`- ${k}: ${groups[k].map((x) => `\`${x}\``).join(', ')}`);
  const soap = Object.values(doc['x-soap-operations'] || {});
  const sv = {};
  for (const o of soap) sv[o['x-verification']] = (sv[o['x-verification']] || 0) + 1;
  lines.push(`- SOAP actions (${soap.length}): ${Object.entries(sv).map(([k, v]) => `${v} ${k}`).join(', ')}`);
  return lines.join('\n');
}

export function strictYamlText(sourceText) {
  return toYaml(buildStrict(parseExact(sourceText)), STRICT_HEADER);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = strictYamlText(fs.readFileSync(SOURCE_YAML, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(STRICT_YAML) ? fs.readFileSync(STRICT_YAML, 'utf8') : '';
    if (cur !== out) { console.log('chomikbox.openapi.yaml is STALE: run node tools/build-strict.mjs'); process.exit(1); }
    console.log('chomikbox.openapi.yaml is up to date');
  } else {
    fs.writeFileSync(STRICT_YAML, out, 'utf8');
    console.log(`wrote ${path.relative(API, STRICT_YAML)} (${out.length} bytes)`);
  }
}
